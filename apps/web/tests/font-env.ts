import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Hermetic fontconfig for Playwright pixel snapshots.
//
// Committed snapshots must render from byte-identical fonts on the delivery
// host and on CI. scripts/provision-snapshot-fonts.sh materializes the
// sha256-pinned set (apps/web/tests/snapshot-fonts.sha256) into
// <repo>/.tools/snapshot-fonts; this module points FONTCONFIG_FILE at a
// generated config that sees ONLY that directory, so distro fonts, Windows
// fonts mounted under WSL, and runner-image drift can never change pixels.
// Generic-family aliases are pinned explicitly for the same reason.
const thisDir = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(thisDir, "..", "..", "..");
const fontDir = path.join(repoRoot, ".tools", "snapshot-fonts");
const manifestFile = path.join(thisDir, "snapshot-fonts.sha256");

export function pinSnapshotFontEnv(): void {
  const names = readFileSync(manifestFile, "utf8")
    .split("\n")
    .filter((line) => line.trim().length > 0 && !line.startsWith("#"))
    .map((line) => line.trim().split(/\s+/)[1]);
  const missing = names.filter((name) => !existsSync(path.join(fontDir, name)));
  if (missing.length > 0) {
    throw new Error(
      `Snapshot fonts missing from ${fontDir}: ${missing.join(", ")}. ` +
        "Run: bash scripts/provision-snapshot-fonts.sh",
    );
  }
  mkdirSync(path.join(fontDir, ".fontconfig-cache"), { recursive: true });
  const conf = path.join(fontDir, "fonts.conf");
  writeFileSync(
    conf,
    [
      '<?xml version="1.0"?>',
      '<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">',
      "<!-- Generated by apps/web/tests/font-env.ts. Hermetic font set for",
      "     Playwright pixel snapshots; do not edit by hand. -->",
      "<fontconfig>",
      `  <dir>${fontDir}</dir>`,
      `  <cachedir>${path.join(fontDir, ".fontconfig-cache")}</cachedir>`,
      '  <alias binding="same">',
      "    <family>sans-serif</family>",
      "    <prefer><family>Liberation Sans</family><family>Noto Sans CJK SC</family></prefer>",
      "  </alias>",
      '  <alias binding="same">',
      "    <family>system-ui</family>",
      "    <prefer><family>Liberation Sans</family><family>Noto Sans CJK SC</family></prefer>",
      "  </alias>",
      '  <alias binding="same">',
      "    <family>serif</family>",
      "    <prefer><family>Liberation Serif</family></prefer>",
      "  </alias>",
      '  <alias binding="same">',
      "    <family>monospace</family>",
      "    <prefer><family>Liberation Mono</family><family>Noto Sans Mono CJK SC</family></prefer>",
      "  </alias>",
      "</fontconfig>",
      "",
    ].join("\n"),
  );
  process.env.FONTCONFIG_FILE = conf;
}
